const goodPlan = `# Plan

## Steps

1. Do the thing.

## File Scope

- src/

## Acceptance Criteria

- The thing is done.

## Validation Commands

- ` + "`true`" + `
`

type fixture struct {
	t    *testing.T
	dir  string
	repo *gitx.Repo
}

func newFixture(t *testing.T) *fixture {
	t.Helper()
	dir := t.TempDir()
	f := &fixture{t: t, dir: dir, repo: &gitx.Repo{Dir: dir}}
	f.git("init", "--initial-branch=main")
	return f
}

func (f *fixture) git(args ...string) string {
	f.t.Helper()
	cmd := exec.Command("git", args...)
	cmd.Dir = f.dir
	out, err := cmd.CombinedOutput()
	if err != nil {
		f.t.Fatalf("git %v: %v: %s", args, err, out)
	}
	return strings.TrimSpace(string(out))
}

func (f *fixture) write(path, content string) {
	f.t.Helper()
	p := filepath.Join(f.dir, path)
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		f.t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
		f.t.Fatal(err)
	}
}

func (f *fixture) commitAll(msg string) {
	f.t.Helper()
	f.git("add", "-A")
	f.git("commit", "-q", "-m", msg)
}

// planOnMain commits a valid plan for id on main and creates branch seed/<id>.
func (f *fixture) planAndBranch(id string) {
	f.t.Helper()
	f.git("checkout", "-q", "main")
	f.write("plans/"+id+".md", goodPlan)
	f.commitAll("plan " + id)
	f.git("checkout", "-q", "-b", "seed/"+id)
}

func (f *fixture) generateAndCommitReceipt(id string) {
	f.t.Helper()
	r, err := Generate(f.repo, id, "main", Options{RunValidation: true, GeneratedBy: "ci"})
	if err != nil {
		f.t.Fatal(err)
	}
	if err := r.WriteFile(f.dir); err != nil {
		f.t.Fatal(err)
	}
	f.commitAll("receipt " + id)
}

func failuresContain(rep *Report, substr string) bool {
	for _, f := range rep.Failures {
		if strings.Contains(f, substr) {
			return true
		}
	}
	return false
}

