// A failing validation command fails verify.
func TestVerifyFailsOnRedValidation(t *testing.T) {
	f := newFixture(t)
	f.write("README.md", "hi\n")
	f.commitAll("init")
	f.git("checkout", "-q", "main")
	f.write("plans/os-6666.md", strings.Replace(goodPlan, "`true`", "`false`", 1))
	f.commitAll("plan os-6666")
	f.git("checkout", "-q", "-b", "seed/os-6666")
	f.write("src/thing.txt", "done\n")
	f.commitAll("implement")
	r, err := Generate(f.repo, "os-6666", "main", Options{RunValidation: true})
	if err != nil {
		t.Fatal(err)
	}
	r.WriteFile(f.dir)
	f.commitAll("receipt")

	rep, err := Verify(f.repo, "os-6666", "main", "seed/os-6666", Options{RunValidation: true})
	if err != nil {
		t.Fatal(err)
	}
	if rep.OK || !failuresContain(rep, "validation command failed") {
		t.Fatalf("red validation not caught: ok=%v failures=%v", rep.OK, rep.Failures)
	}
}

